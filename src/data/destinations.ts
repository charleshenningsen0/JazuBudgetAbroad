export type Region =
  | 'North America'
  | 'Europe'
  | 'Latin America'
  | 'Asia'
  | 'Middle East & Africa'
  | 'Oceania'

/**
 * Cost model per destination, all in USD and based on a *typical student*:
 *   lodging   - per night (hostel / dorm / budget guesthouse / shared room)
 *   food      - per day (groceries + one cheap meal out)
 *   transit   - per day (local transport passes + occasional rideshare)
 *   activities- per day (museums, events, coffee, nightlife)
 *   extras    - per day (SIM card top-ups, souvenirs, laundry, snacks)
 *
 * The spending tier then scales these numbers (see tiers.ts).
 * flight    - indicative round-trip fare from a major US gateway
 * visa      - indicative student visa / entry fee
 */
export interface Destination {
  id: string
  city: string
  country: string
  region: Region
  currency: string
  symbol: string
  /** Local currency units per 1 USD (approximate reference rate). */
  perUSD: number
  lodging: number
  food: number
  transit: number
  activities: number
  extras: number
  flight: number
  visa: number
  /**
   * Destinations sharing a visa group are charged a single visa for the whole
   * trip (all Schengen countries share one). Defaults to the country name.
   */
  visaGroup?: string
  /** Cheap student-friendly food spots / market info for tips. */
  tip: string
}

